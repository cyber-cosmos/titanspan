import assert from "node:assert/strict";
import { mkdtemp, mkdir, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import test from "node:test";

import { validateDocumentationNavigation } from "./check-navigation.mjs";

/**
 * Create and clean up an isolated documentation fixture.
 *
 * @param {(root: string) => Promise<void>} callback Fixture operation.
 * @returns {Promise<void>} Completion of the fixture operation.
 */
async function withDocs(callback) {
  const root = await mkdtemp(path.join(tmpdir(), "titanspan-docs-"));
  try {
    await callback(root);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
}

/**
 * Create Markdown pages in a fixture tree.
 *
 * @param {string} root Documentation fixture root.
 * @param {string[]} paths Relative Markdown paths.
 * @returns {Promise<void>} Completion of the fixture writes.
 */
async function addPages(root, paths) {
  for (const page of paths) {
    const file = path.join(root, page);
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, "---\ntitle: Fixture\n---\n", "utf8");
  }
}

test("accepts complete navigation and autogenerated subdirectories", async () => {
  await withDocs(async (root) => {
    await addPages(root, [
      "index.md",
      "guide.md",
      "architecture/decisions/index.md",
      "architecture/decisions/0001-example.md",
    ]);
    const sidebar = [
      "guide",
      {
        label: "Decision records",
        items: [{ autogenerate: { directory: "architecture/decisions" } }],
      },
    ];

    assert.deepEqual(
      validateDocumentationNavigation(root, sidebar),
      [],
    );
  });
});

test("excludes Starlight's special 404 page from the sidebar", async () => {
  await withDocs(async (root) => {
    await addPages(root, ["index.md", "404.md", "guide.md"]);

    assert.deepEqual(
      validateDocumentationNavigation(root, ["guide"]),
      [],
    );
  });
});

test("reports published pages missing from the sidebar", async () => {
  await withDocs(async (root) => {
    await addPages(root, ["guide.md", "container/scopes.md"]);

    const errors = validateDocumentationNavigation(root, ["guide"]);

    assert.ok(
      errors.some((error) => error.includes("container/scopes.md")),
    );
    assert.ok(
      errors.some((error) => error.includes("missing from the sidebar")),
    );
  });
});

test("reports nonexistent links from sidebar entries and groups", async () => {
  await withDocs(async (root) => {
    await addPages(root, ["guide.md"]);
    const sidebar = [
      { label: "Invalid", link: "/missing-nav/" },
      { label: "Guides", items: ["guide", "missing-sidebar"] },
      { label: "External", link: "https://example.com/" },
    ];

    const errors = validateDocumentationNavigation(root, sidebar);

    assert.ok(errors.some((error) => error.includes("missing-nav")));
    assert.ok(errors.some((error) => error.includes("missing-sidebar")));
  });
});

test("detects duplicate destinations for folder index aliases", async () => {
  await withDocs(async (root) => {
    await addPages(root, ["container/index.md"]);

    const errors = validateDocumentationNavigation(root, [
      "container/",
      "container/index",
    ]);

    assert.ok(errors.some((error) => error.includes("Duplicate sidebar")));
  });
});

test("rejects a missing or malformed sidebar", async () => {
  await withDocs(async (root) => {
    const errors = validateDocumentationNavigation(root, {});

    assert.ok(errors.some((error) => error.includes("sidebar array")));
  });
});

test("reports missing autogenerated directories", async () => {
  await withDocs(async (root) => {
    await addPages(root, ["guide.md"]);

    const errors = validateDocumentationNavigation(root, [
      {
        label: "Missing",
        items: [{ autogenerate: { directory: "missing" } }],
      },
      "guide",
    ]);

    assert.ok(errors.some((error) => error.includes('directory "missing"')));
  });
});
