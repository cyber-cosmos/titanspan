async def test_factory_make_state_sequence_and_create(
    application: Application,
) -> None:
    """Make transient models and create a stateful batch asynchronously.

    Args:
        application: Application configured by the test fixture.
    """
    async with application:
        async with Schema.create("factory_users") as table:
            table.id()
            table.string("name", length=120)
            table.string("email", length=320).unique()
            table.timestamps()

        assert not await FactoryUser.factory().create_many_async(0)
        empty_sync = await anyio.to_thread.run_sync(
            FactoryUser.factory().create_many,
            0,
        )
        assert not empty_sync

        made_callbacks: list[FactoryUser] = []
        factory = (
            FactoryUser.factory()
            .sequence({"name": "Grace"}, {"name": "Linus"})
            .state({"name": lambda index: f"State {index}"})
            .after_making(made_callbacks.append)
        )
        raw_attributes = factory.raw_attributes(index=1)
        assert raw_attributes == {
            "name": "State 1",
            "email": "user-1@example.test",
        }
        assert factory.raw_attributes(
            index=1,
            attributes={"name": "Ada"},
        ) == {
            "name": "Ada",
            "email": "user-1@example.test",
        }
        assert not made_callbacks
        assert await DB.table("factory_users").count_async() == 0

        made = FactoryUser.factory().make()

        assert made.name == "User 0"
        assert not made.exists
        assert await DB.table("factory_users").count_async() == 0

        created = await (
            FactoryUser.factory().state({"name": "Ada"}).create_async()
        )
        assert created.name == "Ada"
        assert created.exists

        batch = await (
            FactoryUser.factory()
            .sequence({"name": "Grace"}, {"name": "Linus"})
            .state(
                {
                    "email": lambda index: (f"batch-{index}@example.test"),
                },
            )
            .count(_EXPECTED_BATCH_COUNT)
            .create_async()
        )

        assert [user.name for user in batch] == [
            "Grace",
            "Linus",
            "Grace",
        ]
        assert (
            await DB.table("factory_users").count_async()
            == _EXPECTED_USER_COUNT
        )


async def test_factory_builds_persists_and_recycles_related_models(
    application: Application,
) -> None:
    """Build transient and persisted graphs through mapped relationships.

    Args:
        application: Application configured by the test fixture.
    """
    async with application:
        async with Schema.create("factory_parents") as table:
            table.id()
            table.string("name", length=120)
            table.timestamps()
        async with Schema.create("factory_children") as table:
            table.id()
            table.foreign_id("parent_id").references("factory_parents")
            table.string("label", length=120)
            table.timestamps()

        with pytest.raises(
            DatabaseFactoryError,
            match="persisted model",
        ):
            FactoryChild.factory().relationship(
                "parent",
                FactoryParent.factory().make(),
            )

        related_create_ids: list[int] = []
        child_factory = FactoryChild.factory().after_creating(
            lambda child: related_create_ids.append(child.id),
        )
        parent_factory = FactoryParent.factory().relationship(
            "children",
            child_factory,
            count=_EXPECTED_RELATED_MODEL_COUNT,
        )

        transient = parent_factory.make()
        assert not transient.exists
        assert len(transient.children) == _EXPECTED_RELATED_MODEL_COUNT
        assert all(not child.exists for child in transient.children)
        assert await DB.table("factory_parents").count_async() == 0
        assert await DB.table("factory_children").count_async() == 0

        created_parent = await parent_factory.create_async()
        assert created_parent.exists
        assert await DB.table("factory_parents").count_async() == 1
        assert (
            await DB.table("factory_children").count_async()
            == _EXPECTED_RELATED_MODEL_COUNT
        )
        assert len(related_create_ids) == _EXPECTED_RELATED_MODEL_COUNT

        recycled_parent = await FactoryParent.factory().create_async(
            {"name": "Recycled parent"},
        )
        child_with_parent = (
            FactoryChild.factory()
            .relationship(
                "parent",
                recycled_parent,
            )
            .make()
        )
        assert child_with_parent.parent is recycled_parent
        assert not child_with_parent.exists
        created_child = (
            await FactoryChild.factory()
            .relationship(
                "parent",
                recycled_parent,
            )
            .create_async()
        )
        assert created_child.exists
        assert created_child.parent.id == recycled_parent.id
        assert (
            await DB.table("factory_parents").count_async()
            == _EXPECTED_RECYCLED_PARENT_COUNT
        )
        assert (
            await DB.table("factory_children").count_async()
            == _EXPECTED_CHILD_COUNT_AFTER_RECYCLE
        )

        with pytest.raises(DatabaseFactoryError, match="count of one"):
            FactoryChild.factory().relationship(
                "parent",
                FactoryParent.factory(),
                count=2,
            )
        with pytest.raises(DatabaseFactoryError, match="compatible mapped"):
            FactoryChild.factory().relationship(
                "parent",
                FactoryChild.factory(),
            )
        with pytest.raises(DatabaseFactoryError, match="compatible mapped"):
            FactoryChild.factory().relationship(
                "missing",
                FactoryParent.factory(),
            )
        with pytest.raises(DatabaseFactoryError, match="compatible mapped"):
            FactoryChild.factory().relationship(
                "parent",
                created_child,
            )
        with pytest.raises(DatabaseFactoryError, match="count of one"):
            FactoryParent.factory().relationship(
                "children",
                created_child,
                count=2,
            )
        with pytest.raises(DatabaseFactoryError, match="compatible mapped"):
            FactoryParent.factory().relationship("children", created_child)
        with pytest.raises(DatabaseFactoryError, match="compatible mapped"):
            FactoryParent.factory().relationship(
                "primary_child",
                created_child,
            ).make()


async def test_factory_builds_and_recycles_many_to_many_models(
    application: Application,
) -> None:
    """Build a mapped pivot graph and reuse persisted collection members.

    Args:
        application: Application configured by the test fixture.
    """
    async with application:
        async with Schema.create("factory_parents") as table:
            table.id()
            table.string("name", length=120)
            table.timestamps()
        async with Schema.create("factory_tags") as table:
            table.id()
            table.string("name", length=120).unique()
            table.timestamps()
        await DB.statement_async(
            "CREATE TABLE factory_parent_tags ("
            "parent_id INTEGER NOT NULL REFERENCES factory_parents(id), "
            "tag_id INTEGER NOT NULL REFERENCES factory_tags(id), "
            "created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, "
            "updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, "
            "PRIMARY KEY(parent_id, tag_id))"
        )

        tag_factory = FactoryTag.factory().state(
            {"name": lambda index: f"Tag {index}"},
        )
        parent_factory = FactoryParent.factory().relationship(
            "tags",
            tag_factory,
            count=_EXPECTED_FACTORY_TAG_COUNT,
        )
        transient = parent_factory.make()
        assert not transient.exists
        assert len(transient.tags) == _EXPECTED_FACTORY_TAG_COUNT
        assert all(not tag.exists for tag in transient.tags)
        assert await DB.table("factory_parent_tags").count_async() == 0

        created_parent = await parent_factory.create_async()
        assert created_parent.exists
        assert len(created_parent.tags) == _EXPECTED_FACTORY_TAG_COUNT
        assert all(tag.exists for tag in created_parent.tags)
        assert await DB.table("factory_parents").count_async() == 1
        assert await DB.table("factory_tags").count_async() == (
            _EXPECTED_FACTORY_TAG_COUNT
        )
        assert await DB.table("factory_parent_tags").count_async() == (
            _EXPECTED_FACTORY_TAG_COUNT
        )

        recycled_tag = created_parent.tags[0]
        recycled_parent = await (
            FactoryParent.factory()
            .relationship("tags", recycled_tag)
            .create_async()
        )
        assert recycled_parent.exists
        assert len(recycled_parent.tags) == 1
        assert recycled_parent.tags[0].id == recycled_tag.id
        assert await DB.table("factory_parents").count_async() == (
            _EXPECTED_FACTORY_PARENT_COUNT
        )
        assert await DB.table("factory_tags").count_async() == (
            _EXPECTED_FACTORY_TAG_COUNT
        )
        assert await DB.table("factory_parent_tags").count_async() == (
            _EXPECTED_FACTORY_PIVOT_COUNT
        )

        def create_sync_recycled_parent() -> FactoryParent:
            """Persist a parent that reuses one loaded tag synchronously.

            The synchronous Database session runs in an AnyIO worker thread.
            """
            return (
                FactoryParent.factory()
                .relationship("tags", recycled_tag)
                .create()
            )

        sync_parent = await anyio.to_thread.run_sync(
            create_sync_recycled_parent,
        )
        assert sync_parent.exists
        assert await DB.table("factory_parents").count_async() == (
            _EXPECTED_SYNC_FACTORY_PARENT_COUNT
        )
        assert await DB.table("factory_parent_tags").count_async() == (
            _EXPECTED_SYNC_FACTORY_PIVOT_COUNT
        )


async def test_factory_builds_nested_mapped_pivot_models(
    application: Application,
) -> None:
    """Persist pivot attributes with a nested association-object factory.

    Args:
        application: Application configured by the test fixture.
    """
    async with application:
        async with Schema.create("factory_parents") as table:
            table.id()
            table.string("name", length=120)
            table.timestamps()
        async with Schema.create("factory_tags") as table:
            table.id()
            table.string("name", length=120).unique()
            table.timestamps()
        async with Schema.create("factory_memberships") as table:
            table.id()
            table.foreign_id("parent_id").references("factory_parents")
            table.foreign_id("tag_id").references("factory_tags")
            table.string("role", length=80)
            table.timestamps()

        tag_factory = FactoryTag.factory().state(
            {"name": lambda index: f"Pivot tag {index}"},
        )
        membership_factory = (
            FactoryMembership.factory()
            .state({"role": lambda index: f"member-{index}"})
            .relationship("tag", tag_factory)
        )
        parent_factory = FactoryParent.factory().relationship(
            "memberships",
            membership_factory,
            count=_EXPECTED_FACTORY_TAG_COUNT,
        )
        transient = parent_factory.make()
        assert not transient.exists
        assert len(transient.memberships) == _EXPECTED_FACTORY_TAG_COUNT
        assert all(
            not membership.exists for membership in transient.memberships
        )
        assert all(
            not membership.tag.exists for membership in transient.memberships
        )
        assert await DB.table("factory_memberships").count_async() == 0

        created_parent = await parent_factory.create_async()
        assert created_parent.exists
        assert [
            membership.role for membership in created_parent.memberships
        ] == [
            "member-0",
            "member-1",
        ]
        assert all(
            membership.exists for membership in created_parent.memberships
        )
        assert all(
            membership.tag.exists for membership in created_parent.memberships
        )
        assert await DB.table("factory_parents").count_async() == 1
        assert await DB.table("factory_memberships").count_async() == (
            _EXPECTED_FACTORY_TAG_COUNT
        )
        assert await DB.table("factory_tags").count_async() == (
            _EXPECTED_FACTORY_TAG_COUNT
        )


async def test_factory_callbacks_observe_make_and_commit_boundaries(
    application: Application,
) -> None:
    """Run factory callbacks at their documented lifecycle boundaries.

    Args:
        application: Application configured by the test fixture.
    """
    async with application:
        async with Schema.create("factory_users") as table:
            table.id()
            table.string("name", length=120)
            table.string("email", length=320).unique()
            table.timestamps()

        made_states: list[bool] = []
        created_states: list[bool] = []
        batch = (
            FactoryUser.factory()
            .count(1)
            .after_making(lambda user: made_states.append(user.exists))
            .after_creating(lambda user: created_states.append(user.exists))
        )

        async with DB.transaction_async():
            models = await batch.create_async(
                {"email": "committed@example.test"},
            )
            assert made_states == [False]
            assert created_states == []
            assert models[0].exists

        assert created_states == [True]

        created_states.clear()
        with pytest.raises(RuntimeError, match=_ROLLBACK_MESSAGE):
            await _create_then_fail(batch)

        assert created_states == []
        assert await DB.table("factory_users").count_async() == 1


async def test_factory_rejects_recycled_models_from_another_application(
    application: Application,
    tmp_path: Path,
) -> None:
    """Keep recycled factory relations within their owning application.

    Args:
        application: First isolated SQLite application.
        tmp_path: Shared application root for the second service instance.
    """
    async with application:
        async with Schema.create("factory_parents") as table:
            table.id()
            table.string("name", length=120)
            table.timestamps()
        async with Schema.create("factory_children") as table:
            table.id()
            table.foreign_id("parent_id").references("factory_parents")
            table.string("label", length=120)
            table.timestamps()
        parent = await FactoryParent.factory().create_async()

    second_application = Application(
        base_path=tmp_path,
        config={
            "database": {
                "default": "sqlite",
                "connections": {
                    "sqlite": {
                        "driver": "sqlite",
                        "database": "database/factories.sqlite",
                    },
                },
            },
        },
        service_providers=(DatabaseServiceProvider(),),
    )
    async with second_application:
        child_factory = FactoryChild.factory().relationship("parent", parent)
        with pytest.raises(DatabaseTransactionOwnershipError):
            await child_factory.create_async()
        assert await DB.table("factory_children").count_async() == 0


def test_sync_factory_uses_application_owned_transaction() -> None:
    """Persist synchronous factory batches through the same Database service.

    Args:
        No parameters are required; the native test helper owns the app.
    """
    test_app = ApplicationTest(
        config={
            "database": {
                "default": "sqlite",
                "connections": {
                    "sqlite": {
                        "driver": "sqlite",
                        "database": "database/sync-factories.sqlite",
                    },
                },
            },
        },
        service_providers=(DatabaseServiceProvider(),),
    )
    with test_app, test_app.application.context():
        with Schema.create("factory_users") as table:
            table.id()
            table.string("name", length=120)
            table.string("email", length=320).unique()

            table.timestamps()

        transient = FactoryUser.factory().count(_SYNC_BATCH_COUNT).make()
        assert len(transient) == _SYNC_BATCH_COUNT
        assert all(not user.exists for user in transient)
        assert DB.table("factory_users").count() == 0

        created = FactoryUser.factory().count(_SYNC_BATCH_COUNT).create()

        assert len(created) == _SYNC_BATCH_COUNT
        assert DB.table("factory_users").count() == _SYNC_BATCH_COUNT


async def _create_then_fail(
    batch: FactoryBatch[FactoryUser],
) -> None:
    """Create a batch in a transaction and raise to trigger rollback.

    Args:
        batch: One configured test batch with post-create callbacks.
    """
    async with DB.transaction_async():
        await batch.create_async({"email": "rolled-back@example.test"})
        raise RuntimeError(_ROLLBACK_MESSAGE)
